// Generate a scaled battle sprite from a 16x16 source
// This produces a 48x48 (3x scale) or 56x56 array from the overworld sprite
function scaleSpriteData(source, sourceWidth, targetWidth) {
  const scale = Math.floor(targetWidth / sourceWidth);
  const target = new Array(targetWidth * targetWidth).fill(-1);
  for (let sy = 0; sy < sourceWidth; sy++) {
    for (let sx = 0; sx < sourceWidth; sx++) {
      const val = source[sy * sourceWidth + sx];
      if (val < 0) continue;
      for (let dy = 0; dy < scale; dy++) {
        for (let dx = 0; dx < scale; dx++) {
          const tx = sx * scale + dx;
          const ty = sy * scale + dy;
          if (tx < targetWidth && ty < targetWidth) {
            target[ty * targetWidth + tx] = val;
          }
        }
      }
    }
  }
  return target;
}

// Tiger battle back (48x48) — 3x scaled from TIGER_BACK
export const TIGER_BATTLE_BACK = scaleSpriteData(TIGER_BACK, 16, 48);

// NPC battle sprites (56x56) — ~3.5x scaled from 16x16 overworld sprites
// We scale to 48 first (3x), then center in 56x56
function createBattleSprite(source16) {
  const scaled = scaleSpriteData(source16, 16, 48);
  const target = new Array(56 * 56).fill(-1);
  const offset = 4; // center 48 in 56
  for (let y = 0; y < 48; y++) {
    for (let x = 0; x < 48; x++) {
      target[(y + offset) * 56 + (x + offset)] = scaled[y * 48 + x];
    }
  }
  return target;
}

